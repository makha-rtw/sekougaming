export const DEFAULT_PLAYER_COUNT = 8;

export function getDefaultRoleConfig(totalPlayers: number): Record<RoleId, number> {
  const config: Record<RoleId, number> = {
    loup_garou: totalPlayers <= 6 ? 1 : totalPlayers <= 11 ? 1 : totalPlayers <= 16 ? 2 : 3,
    grand_mechant_loup: totalPlayers >= 8 ? 1 : 0,
    loup_blanc: 0,
    voyante: 1,
    petite_fille: totalPlayers >= 6 ? 1 : 0,
    renard: totalPlayers >= 8 ? 1 : 0,
    sorciere: 1,
    salvateur: totalPlayers >= 6 ? 1 : 0,
    ange: totalPlayers >= 12 ? 1 : 0,
    chasseur: totalPlayers >= 10 ? 1 : 0,
    cupidon: totalPlayers >= 10 ? 1 : 0,
    voleur: totalPlayers >= 12 ? 1 : 0,
    pyromane: totalPlayers >= 14 ? 1 : 0,
    villageois: 0,
  };

  // Calculate sum of non-villager roles
  const specialCount = Object.entries(config)
    .filter(([key]) => key !== 'villageois')
    .reduce((sum, [, val]) => sum + val, 0);

  config.villageois = Math.max(0, totalPlayers - specialCount);

  return config;
}
